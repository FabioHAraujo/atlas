// Reads assets/logo.svg (the Atlas mark: hand-cut tiles) and writes src/lib/onboarding/intro/mark.ts: each tile's
// path data and bounding box, so the welcome intro animates the real logo, not a redrawn one. Committed output
// (design data, not a build artefact); intro/mark.test.ts fails if it drifts from the SVG.
// Run: bun scripts/gen-mark.ts
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const svg = await readFile(join(import.meta.dir, "../../../assets/logo.svg"), "utf8");
const view = /viewBox="0 0 (\d+) (\d+)"/.exec(svg);
if (!view) throw new Error("logo.svg has no 0 0 W H viewBox");
const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]!);

/** Bounding box of an absolute-coordinate path (the traced logo uses only M/L/C/Z with absolute numbers). */
function box(d: string) {
	const n = (d.match(/-?\d+\.?\d*/g) ?? []).map(Number);
	const xs = n.filter((_, i) => i % 2 === 0);
	const ys = n.filter((_, i) => i % 2 === 1);
	const [x0, x1, y0, y1] = [Math.min(...xs), Math.max(...xs), Math.min(...ys), Math.max(...ys)];
	return {
		cx: +((x0 + x1) / 2).toFixed(1),
		cy: +((y0 + y1) / 2).toFixed(1),
		w: +(x1 - x0).toFixed(1),
		h: +(y1 - y0).toFixed(1),
	};
}

const rows = paths.map((d, id) => ({ id, ...box(d), d }));
const body = `// GENERATED by scripts/gen-mark.ts from assets/logo.svg. Do not edit; run \`bun scripts/gen-mark.ts\`.
export const MARK_VIEW = { w: ${view[1]}, h: ${view[2]} } as const;

/** One entry per <path> of the logo, in file order: id = index, bounding box in logo units, and the path data. */
export const MARK: { id: number; cx: number; cy: number; w: number; h: number; d: string }[] = ${JSON.stringify(rows, null, "\t")};
`;
await writeFile(join(import.meta.dir, "../src/lib/onboarding/intro/mark.ts"), body);
console.log(`wrote ${rows.length} tiles`);
